"""中国大陆 26 个省级行政区身后事知识库数据表。

## 为什么用数据表 + 渲染器，而不是逐个手写 Markdown

`knowledge/regions/CN/*.md` 的内容可分为两类：

1. **全国统一的法律/政策口径**（约占 70%）——《民法典》继承顺序与遗嘱形式、
   5 万元以下存款免公证提取（金融监管总局 2024 年新规）、法定继承契税免征、
   中国未开征遗产税、遗产债务有限清偿、110/120/119/12345/12333/12329/12348
   等全国统一号码。这部分**必须各省一致**，手写 26 份必然产生口径漂移。
2. **省级差异化事实**（约占 30%）——火葬区/土葬改革区划分、少数民族殡葬政策、
   "身后一件事"联办、小客车指标继承、计划单列市社保独立、边境/侨乡/兵团等
   特殊情形。这部分逐省录入本数据表。

## 数据可信度纪律（对齐 rules/ 与 SCHEMA.md）

- **绝不编造电话号码**：只写全国统一号码；省级机构电话一律写"拨打 12345 核实"。
- **绝不编造具体金额/比例**：丧葬费、抚恤金、生态葬补贴等只写计算口径，
  具体数额要求用户向 12333 / 12345 核实。
- **URL 只收录已联网核验的省级政府门户**（26/26 已 curl + DNS 核验）。
  厅局子域普遍存在改版失效与 DNS 泛解析，一律不收录，改为引导从省门户进入。
- 所有省级条目统一标注"数据可信度: 中"，并在免责区块要求办理前核实。
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Province:
    """一个省级行政区的差异化事实。"""

    key: str
    """文件名（不含扩展名），用国家内通用拼音缩写，对齐 SCHEMA.md。"""

    name: str
    """全称，如「天津市」。"""

    short: str
    """简称，用于正文行文，如「天津」。"""

    iso: str
    """ISO 3166-2 代码，如 CN-TJ。"""

    portal: str
    """省级政府门户（已联网核验）。"""

    kind: str
    """直辖市 / 省 / 自治区。"""

    sub_unit: str
    """下辖行政单位说明，如「16 个区」「11 个设区市」。"""

    one_thing: list[str]
    """「身后一件事 / 死亡一件事」联办现状。"""

    cremation: list[str]
    """火葬区与遗体处理的省内政策。"""

    ethnic: list[str]
    """少数民族殡葬政策（无则留空）。"""

    eco: list[str]
    """生态葬与惠民殡葬。"""

    plate: list[str]
    """小客车指标 / 车辆过户的省内特殊点。"""

    geo: list[str]
    """异地、跨境、地理造成的特殊情形。"""

    medical: list[str]
    """医保体系与就医的省内特点。"""

    social: list[str]
    """社保 / 公积金结算的省内特点（含计划单列市独立统筹）。"""

    inherit: list[str]
    """遗产继承与不动产的省内特殊点。"""

    hotline: list[str] = field(default_factory=list)
    """额外热线说明（不得编造号码，只写全国统一号码或引导核实）。"""


