def bullets(items: list[str], indent: int = 0) -> list[str]:
    """把字符串列表渲染为 Markdown 无序列表。"""
    pad = " " * indent
    return [f"{pad}- {item}" for item in items]


_FINANCIAL_HINTS = ("存款", "银行", "金融", "证券", "股权", "股票", "信用社")
_PROPERTY_HINTS = ("房", "宅基地", "土地", "不动产", "林", "草场", "承包", "拆迁", "小产权")


def split_inherit(p: Province) -> tuple[list[str], list[str], list[str]]:
    """把 `inherit` 条目分流到阶段5（金融）、阶段6（不动产）、阶段7（通用）。

    避免同一条事实在三个阶段重复出现。分流按关键词判定，
    金融优先于不动产，都不命中的归入阶段7 的「当地特殊规定」。
    """
    financial: list[str] = []
    property_: list[str] = []
    general: list[str] = []
    for item in p.inherit:
        if any(hint in item for hint in _FINANCIAL_HINTS):
            financial.append(item)
        elif any(hint in item for hint in _PROPERTY_HINTS):
            property_.append(item)
        else:
            general.append(item)
    return financial, property_, general


def gov_word(p: Province) -> str:
    """省 / 市 / 自治区 的行文用词。"""
    if p.kind == "直辖市":
        return "市"
    if p.kind == "自治区":
        return "自治区"
    return "省"


def level(p: Province) -> str:
    """统筹层级用词，如「市级统筹」「省级统筹」。"""
    return f"{gov_word(p)}级"


